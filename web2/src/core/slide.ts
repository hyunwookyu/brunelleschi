// 겹을 깔고 치우는 동작(web2-40 2번) — **표현만**이다. 기하·판정·저장 어느 것도 이
// 창을 안 읽는다(`SETTLE_ANIM_MS`가 낸 선례 그대로 — 전이 중에도 그 겹은 이미 거기 있다).
//
// 사람: 「이거 깔거나 치울 때, 종이를 까는 모션이 있으면 좋겠다. 전자책에서 페이지
//        넘기는 모션을 활용해볼 수 있다.」
//
// 지시가 그 자리에서 갈랐다 — **동작은 안 가져오고 앞 가장자리의 표현만 가져온다**:
// 롤에서 뽑아 덮는 것이므로 실물에 가까운 것은 **한쪽에서 밀려 들어오는** 쪽이고,
// 전자책의 페이지 넘김은 경첩처럼 접히는 동작이라 그대로 쓰면 종이가 어디선가 돌아
// 나오는 것처럼 보인다. 가져오는 것은 **살짝 말린 앞 가장자리의 그림자** — 그것이
// 종이의 두께를 읽히게 하는 부분이다.
//
// ── 불변식(지시 게이트) ───────────────────────────────────────────────────────
//  ㉠ **끝나면 «없던 것»이다** — `away()`가 정확히 0을 내고 말린 그림자도 0이라
//     동작이 끝난 화면이 동작 없이 얹은 화면과 **픽셀로 같다**(팔이 그것을 잰다).
//  ㉡ **입력을 안 막는다** — 이 파일에 «막는다»가 없다. 획이 들어오면 부르는 쪽이
//     `settle`로 창을 즉시 닫는다(끝까지 기다리지 않는다).
//  ㉢ **같은 쪽에서 들어온다** — 방향은 `SLIDE_FROM` 하나이고 겹마다 안 갈린다
//     (장마다 방향이 달라지면 어지럽다 — 지시 문면).

/** 방향 — `in`은 깔기(밀려 들어온다), `out`은 치우기(같은 쪽으로 물러난다) */
export type SlideDir = 'in' | 'out'

/** 한 겹의 동작 — 시작 시각과 방향뿐이다(진행도는 «지금»에서 계산한다: 파생 무저장) */
export interface Slide { t0: number; dir: SlideDir }

/** **들어오는 쪽 — 왼쪽 하나다.** 겹이 여러 장이어도 같은 쪽에서 들어온다(지시 문면).
 *  왼쪽인 근거: 겹을 얹는 자리 둘(종속 탭 「+」·손 띠의 롤통)이 **둘 다 화면 왼쪽 위**라
 *  종이가 그 롤에서 뽑혀 나오는 것으로 읽힌다. */
export const SLIDE_FROM = 'left' as const

const clamp01 = (v: number): number => (v < 0 ? 0 : v > 1 ? 1 : v)

/** 진행도 0..1 — 창이 지났으면 정확히 1(㉠의 근거) */
export const slideT = (t0: number, now: number, ms: number): number =>
  ms <= 0 ? 1 : clamp01((now - t0) / ms)

/** 감속 곡선 — 종이는 **밀려 들어와 자리에 놓인다**(등속이면 기계가 미는 것으로 읽힌다).
 *  3제곱 ease-out은 표준 감속이고 새 기제가 아니다. */
export const slideEase = (t: number): number => 1 - (1 - t) ** 3

/** **덜 온 정도** 0..1 — 0이면 제자리, 1이면 화면 밖.
 *  깔기는 1 → 0으로, 치우기는 0 → 1로 간다(같은 쪽 · 반대 방향 — 지시 문면). */
export function slideAway(s: Slide, now: number, ms: number): number {
  const e = slideEase(slideT(s.t0, now, ms))
  return s.dir === 'in' ? 1 - e : e
}

/** 그 동작이 아직 도는가 — 프레임 고리가 이것을 보고 계속 다시 그린다.
 *  ⚠ **치우기는 끝에서도 «돈다»고 안 한다**: 창이 지나면 유령이 걷히고 그릴 것이 없다. */
export const slideRunning = (s: Slide, now: number, ms: number): boolean =>
  slideT(s.t0, now, ms) < 1

/** **말린 자리가 다 펴지는 «덜 온 정도»** — `away`가 이 아래로 내려가면 그늘이 잦아든다.
 *
 *  ⚠ **`curl = away`는 틀렸다**(첫 판이 그랬고 화면으로 잡았다 — NOTES 40-2 D-1):
 *  그러면 그늘이 가장 짙은 순간이 종이가 **화면 밖에 있는 순간**이고, 정작 종이가 보이는
 *  대역(`away` 0.3 아래)에서는 알파가 0.05까지 내려가 **아무것도 안 읽힌다**.
 *  실제로 그렇게 났다 — 잡은 프레임(`away` = 0.295)에서 앞 가장자리가 맨 종이와 같았다.
 *  0.2인 근거: 감속 곡선이 `away = (1−t)³`이므로 `away = 0.2`는 **t = 0.42**다 —
 *  그늘이 **동작의 뒤쪽 58%에 걸쳐** 펴진다. 「밀려 들어와 자리에 놓이면서 펴진다」가
 *  그 시간 배분이고, 끝에서 **정확히 0**이 되므로 ㉠도 그대로 선다. */
const CURL_FLAT_AT = 0.2

/** **말린 앞 가장자리의 짙기** 0..1 — 움직이는 동안 짙고 자리에 놓이며 펴진다.
 *  제자리(`away = 0`)에서 **정확히 0**이다(㉠ — 픽셀 동일의 산술 뿌리).
 *  앞 가장자리는 **들어올 때 앞섰던 그 변**이고 물러날 때도 같은 변이다(종이의 성질이지
 *  진행 방향의 성질이 아니다) — `SLIDE_FROM`이 왼쪽이므로 **오른쪽 변**이다. */
export const slideCurl = (away: number): number => clamp01(away / CURL_FLAT_AT)
