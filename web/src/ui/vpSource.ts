// **화면의 소실점은 하나의 출처에서 온다**(2026-08-20 17차, 사람 지시).
//
// 사용자 보고: *"스냅이 쓰는 소실점과 화면에 표시된 소실점이 다르다. 축 스냅을 켜고
// 그으면 선들이 한 점으로 모이는데 그 점이 화면에 표시된 소실점이 아니다."*
//
// 재현(수리 전, `e2e/vp_source.spec.ts`): 카메라가 서 있고 **핀이 아닌** 시점에서
//   · 표시(소실점 표식·`drawHorizon`·격자)는 `viewOverlayCtx().vps` = **지금 시점의 투영**
//   · 스냅(`resolve2d` → `dirSnap2dCore` → `vpDirSnap`)은 `cam.vps()` = **확정 시점의 값**
// 을 읽었다. 둘은 자세가 항등일 때만 같고, 돌아가면 갈린다 — 실측 격차가 화면 폭을 넘었다.
//
// **같은 사실을 두 곳이 알면 어긋난다.** 여기가 그 하나의 자리다: 화면에 그리는 쪽도
// 스냅하는 쪽도 이 함수를 지난다(#17 — 앱 경로 하나).
//
// ---------------------------------------------------------------- 어느 값이 맞는가
//
// **지금 시점의 투영이 맞다.** 사용자가 겨냥하는 것은 눈앞의 화면이고, 3D 축 스냅
// (`snapToAxis`)은 이미 그 시점의 축 방향(`frame().ctx.axisDirs`)을 쓴다. `cam.vps()`는
// **확정 시점(핀)의 화면 좌표**라, 돌린 화면에서는 그 자리에 아무것도 없다.
// 핀·확정 전에는 둘이 같은 값이므로(자세가 항등이다) 이 규칙은 그때 항등이다.
import type { Pt2 } from "../s3d/camera.js";

/** 지금 화면이 어떤 상태인가 — 이 셋이 출처를 정한다. */
export interface VpSourceState {
  /** 규칙 상태의 소실점(`CamState.vps()`) — 확정 시점의 화면 좌표. */
  camVps: (Pt2 | null)[];
  /** 지금 시점의 소실점(`frame().ctx.vps`). 시점 문맥이 없으면 `null`. */
  viewVps: (Pt2 | null)[] | null;
  /** 확정 카메라에 물려 있는가(자세 항등). 물려 있으면 두 값이 같다. */
  pinned: boolean;
}

/**
 * **지금 화면의 소실점.** 표시와 스냅이 **함께** 이것을 읽는다.
 *
 * `viewVps`가 없거나(카메라가 아직 안 섰다) 핀이면 규칙의 값이다 — 그때는 자세가
 * 항등이라 두 값이 같고, 낡을 여지가 없다.
 *
 * `legacy`는 **측정 스위치**다(#30) — `false`면 수리 전 거동(스냅이 언제나 `camVps`)을
 * 되살린다. 회귀 팔이 "버그를 되살려 실제로 잡는지" 확인하는 데 쓴다.
 */
export function screenVps(s: VpSourceState, legacy = false): (Pt2 | null)[] {
  if (legacy) return s.camVps;
  return !s.pinned && s.viewVps ? s.viewVps : s.camVps;
}
